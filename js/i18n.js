'use strict';

/**
 * @file i18n.js - Localisation engine
 *
 * Gettext-style translation: the English text is the key. `tr('Waiting for {0}', name)` returns the
 * translation of that sentence for the current language (or the English text itself when there is
 * none) with {0}, {1}... replaced by the arguments. Static text in index.html needs no markup: the
 * DOM walker `translateDom()` finds text nodes and placeholder/title/aria-label attributes whose
 * text has a translation and swaps them (the English original is remembered so switching back
 * works).
 *
 * Adding a language: create js/lang-xx.js that sets `I18N.xx = { 'English text': 'translation' }`,
 * register its display name in `LANGS`, and add the file to index.html after this one.
 *
 * Text that comes from game data (team names, worm names, weapon names) is translated at the
 * point of display, never stored, so online players can each use their own language.
 *
 * Depends on: util
 * Globals defined: LANGS, I18N, LANG, tr, wname, setLang, translateDom, initLang, onLang
 */

/* ===== Localisation ===== */

/** Languages offered in the menu: code -> name in that language. */
const LANGS = { en: 'English', it: 'Italiano' };
/** Dictionaries by language code: { 'English source text': 'translation' }. English needs none. */
const I18N = {};
/** Current language code. */
let LANG = 'en';
/** Callbacks run after the language changes (the HUD, menu and so on re-render themselves). */
const langHooks = [];
/** Registers a function to call whenever the language changes. */
const onLang = fn => langHooks.push(fn);

/**
 * Translates an English source string and fills in {0}, {1}... placeholders.
 * @param {string} src English text (also the fallback)
 * @param {...(string|number)} args values for the placeholders
 * @returns {string}
 */
function tr(src, ...args) {
  const d = I18N[LANG];
  let s = (d && d[src]) || src;
  if (args.length) s = s.replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? args[i] : m));
  return s;
}
/** Display name of a weapon in the current language. */
const wname = id => tr(WEAPONS[id] ? WEAPONS[id].name : String(id));

/**
 * Elements whose content is generated by the game (already translated) and must be skipped,
 * by id here or with a `data-nt` attribute ("not translated by the DOM walker") in the markup.
 */
const DOM_SKIP = new Set(['teamRows', 'wgrid', 'lobbyList', 'log', 'msg', 'teamsbar', 'touch']);
/** Attributes that carry user-visible text. */
const DOM_ATTRS = ['placeholder', 'title', 'aria-label'];
/** Collapses runs of whitespace so multi-line HTML text matches a one-line dictionary key. */
const collapse = s => s.replace(/\s+/g, ' ').trim();

/**
 * Walks the static page and applies the current language. Original English text is kept on the
 * nodes (`__en`) and in `data-en-*` attributes so the walk is repeatable in any direction.
 * @param {Node} [root] subtree to translate (default: document.body)
 * @param {Object} [report] when given, collects source texts that have no translation
 */
function translateDom(root = document.body, report = null) {
  const d = I18N[LANG],
    walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
      acceptNode: n =>
        n.nodeType === 1 &&
        (DOM_SKIP.has(n.id) ||
          n.hasAttribute('data-nt') ||
          n.tagName === 'SCRIPT' ||
          n.tagName === 'STYLE')
          ? NodeFilter.FILTER_REJECT
          : NodeFilter.FILTER_ACCEPT,
    });
  const miss = (src, where) => {
    if (report && src && /[A-Za-z]{2,}/.test(src) && !(I18N.it && I18N.it[src]))
      report[src] = where;
  };
  for (let n = walker.currentNode; n; n = walker.nextNode()) {
    if (n.nodeType === 3) {
      if (n.__en === undefined) n.__en = n.nodeValue;
      const src = collapse(n.__en);
      if (!src) continue;
      miss(src, 'text');
      const tr = d && d[src];
      if (tr) {
        const lead = /^\s/.test(n.__en) ? ' ' : '',
          trail = /\s$/.test(n.__en) ? ' ' : '';
        n.nodeValue = lead + tr + trail;
      } else n.nodeValue = n.__en;
    } else if (n.nodeType === 1) {
      for (const a of DOM_ATTRS) {
        if (!n.hasAttribute(a) && n.dataset['en' + a.replace('-', '')] === undefined) continue;
        const key = 'en' + a.replace('-', '');
        if (n.dataset[key] === undefined) n.dataset[key] = n.getAttribute(a);
        const src = n.dataset[key];
        miss(src, a);
        n.setAttribute(a, (d && d[src]) || src);
      }
    }
  }
}

/**
 * Switches language: stores the choice, retranslates the page and notifies the hooks.
 * @param {string} code key of LANGS
 */
function setLang(code) {
  if (!LANGS[code]) code = 'en';
  LANG = code;
  document.documentElement.lang = code;
  try {
    localStorage.setItem('wormgeddon.lang', code);
  } catch (e) {}
  document.title = tr('Wormgeddon');
  translateDom();
  const sel = document.getElementById('oLang');
  if (sel) sel.value = code;
  langHooks.forEach(fn => fn(code));
}
/** Picks the saved language, else the browser language (Italian if it starts with "it"), else English. */
function initLang() {
  let code = null;
  try {
    code = localStorage.getItem('wormgeddon.lang');
  } catch (e) {}
  if (!LANGS[code]) code = /^it\b/i.test(navigator.language || '') ? 'it' : 'en';
  return code;
}
